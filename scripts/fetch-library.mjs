// Downloads the Nintendo game library and saves it to data/library.js.
//
// Your keys are only read here, on your machine (or in a GitHub Action).
// The website itself only loads the saved data file, so keys are never sent to visitors.
//
//   node scripts/fetch-library.mjs          update: new releases + anything changed since last run
//   node scripts/fetch-library.mjs --full   rebuild everything (the first run does this automatically)
//
// Data source (put ONE of these in .env; IGDB is used if both are present):
//   IGDB_CLIENT_ID + IGDB_CLIENT_SECRET   free, from https://dev.twitch.tv/console
//   RAWG_API_KEY                          free, from https://rawg.io/apidocs
//
// Optional:
//   MIN_RATINGS   IGDB: skip games with fewer user/critic ratings than this, unless new or upcoming (default 2)
//   MIN_ADDED     RAWG: skip games added to fewer RAWG libraries than this (default 15)
//   MAX_PAGES     safety cap on pages per run (default 150)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
loadEnv(path.join(root, ".env"));

const env = (k) => (process.env[k] || "").trim();
const placeholder = (v) => !v || /^paste-|^your-/i.test(v);
const OUT = path.join(root, "data", "library.js");
const FULL_FLAG = process.argv.includes("--full");
const MAX_PAGES = Number(env("MAX_PAGES") || 150);
const DAY = 864e5;
const isoDay = (d) => d.toISOString().slice(0, 10);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let requests = 0;

// Our platform ids -> lowercase names the databases use.
const PLATFORM_NAMES = {
  switch2: ["nintendo switch 2", "switch 2"],
  switch: ["nintendo switch"],
  wiiu: ["wii u"],
  wii: ["wii"],
  "3ds": ["nintendo 3ds", "new nintendo 3ds"],
  ds: ["nintendo ds", "nintendo dsi"],
  gc: ["gamecube", "nintendo gamecube"],
  n64: ["nintendo 64"],
  gba: ["game boy advance"],
  snes: ["snes", "super nintendo", "super nintendo entertainment system"],
  gb: ["game boy", "game boy color"],
  nes: ["nes", "nintendo entertainment system"],
};

function matchPlatform(name) {
  const n = String(name).toLowerCase().trim();
  for (const [ours, names] of Object.entries(PLATFORM_NAMES)) if (names.includes(n)) return ours;
  return null;
}

function loadEnv(file) {
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/i);
    if (m && !line.trim().startsWith("#") && process.env[m[1]] === undefined) {
      process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  }
}

function readExisting() {
  if (!fs.existsSync(OUT)) return null;
  const text = fs.readFileSync(OUT, "utf8");
  try {
    const data = JSON.parse(text.slice(text.indexOf("=") + 1).trim().replace(/;\s*$/, ""));
    if (!data || !Array.isArray(data.games)) return null;
    let summaries = {};
    try { summaries = JSON.parse(fs.readFileSync(path.join(root, "data", "summaries.json"), "utf8")); } catch { /* none yet */ }
    data.games.forEach((g) => { if (summaries[g.id] && !g.sm) g.sm = summaries[g.id]; });
    return data;
  } catch {
    return null;
  }
}

function upsert(map, game) {
  if (!game || !game.p.length) return;
  const prev = map.get(game.id);
  if (prev) game.p = [...new Set([...prev.p, ...game.p])];
  map.set(game.id, game);
}

const SUMMARIES = path.join(root, "data", "summaries.json");

function save(games, source) {
  const list = [...games.values()].sort((a, b) => (b.a || 0) - (a.a || 0));
  // Descriptions go in a separate file the site only loads when a game is opened.
  const summaries = {};
  const lean = list.map(({ sm, ...g }) => {
    if (sm) summaries[g.id] = sm;
    return g;
  });
  const payload = { updated: new Date().toISOString(), source, count: lean.length, games: lean };
  fs.writeFileSync(OUT, `/* Generated by scripts/fetch-library.mjs from ${source}. Do not edit by hand. */\nwindow.LIBRARY = ` + JSON.stringify(payload) + ";\n");
  fs.writeFileSync(SUMMARIES, JSON.stringify(summaries));
  return { count: lean.length, kb: Math.round(fs.statSync(OUT).size / 1024) };
}

const short = (text, max = 320) => {
  if (!text) return null;
  const t = String(text).replace(/\s+/g, " ").trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max);
  const end = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf("! "), cut.lastIndexOf("? "));
  return (end > max * 0.5 ? cut.slice(0, end + 1) : cut.replace(/\s+\S*$/, "") + "…");
};

/* ==========================================================================
   IGDB (Twitch)
   ========================================================================== */

async function runIGDB(existing) {
  const CLIENT_ID = env("IGDB_CLIENT_ID");
  const SECRET = env("IGDB_CLIENT_SECRET");
  const MIN_RATINGS = Number(env("MIN_RATINGS") || 2);

  const tokenRes = await fetch("https://id.twitch.tv/oauth2/token?" + new URLSearchParams({
    client_id: CLIENT_ID, client_secret: SECRET, grant_type: "client_credentials",
  }), { method: "POST" });
  requests++;
  if (!tokenRes.ok) {
    throw new Error(`Twitch rejected the Client ID / Secret (HTTP ${tokenRes.status}). Check IGDB_CLIENT_ID and IGDB_CLIENT_SECRET in .env.`);
  }
  const { access_token: token } = await tokenRes.json();

  let last = 0;
  async function q(endpoint, body) {
    for (let attempt = 1; ; attempt++) {
      const wait = 270 - (Date.now() - last); // IGDB allows 4 requests per second
      if (wait > 0) await sleep(wait);
      last = Date.now();
      requests++;
      const res = await fetch(`https://api.igdb.com/v4/${endpoint}`, {
        method: "POST",
        headers: { "Client-ID": CLIENT_ID, Authorization: `Bearer ${token}`, Accept: "application/json" },
        body,
      });
      if (res.ok) return res.json();
      if ((res.status === 429 || res.status >= 500) && attempt < 6) { await sleep(800 * attempt); continue; }
      const detail = await res.text().catch(() => "");
      throw new Error(`IGDB ${endpoint} failed: HTTP ${res.status} ${detail.slice(0, 300)}`);
    }
  }

  // Resolve platform ids by name.
  const platforms = await q("platforms", "fields id,name; limit 500;");
  const igdbToOurs = new Map();
  for (const p of platforms) {
    const ours = matchPlatform(p.name);
    if (ours) igdbToOurs.set(p.id, ours);
  }
  const found = [...new Set(igdbToOurs.values())];
  const missing = Object.keys(PLATFORM_NAMES).filter((p) => !found.includes(p));
  console.log(`Matched ${found.length} Nintendo systems on IGDB.` + (missing.length ? ` Not found: ${missing.join(", ")}` : ""));
  const ids = [...igdbToOurs.keys()].join(",");

  const MODES = { "single-player": "solo", multiplayer: "multi", "co-operative": "coop", "split-screen": "local" };
  const FIELDS = [
    "name", "slug", "first_release_date", "platforms", "genres.name", "cover.image_id",
    "aggregated_rating", "aggregated_rating_count", "total_rating", "total_rating_count", "hypes",
    "game_modes.slug", "involved_companies.developer", "involved_companies.company.name", "summary", "updated_at",
  ].join(",");

  function compact(g) {
    const p = [...new Set((g.platforms || []).map((id) => igdbToOurs.get(id)).filter(Boolean))];
    const dev = (g.involved_companies || []).find((c) => c.developer)?.company?.name || null;
    const critics = g.aggregated_rating_count >= 3 ? Math.round(g.aggregated_rating) : null;
    return {
      id: g.slug,
      t: g.name,
      d: g.first_release_date ? isoDay(new Date(g.first_release_date * 1000)) : null,
      p,
      g: [...new Set((g.genres || []).map((x) => x.name.replace(/ \(.*\)$/, "")))],
      s: critics,
      r: g.total_rating ? Math.round(g.total_rating / 2) / 10 : 0,
      rc: g.total_rating_count || 0,
      a: (g.total_rating_count || 0) + (g.hypes || 0),
      i: g.cover?.image_id ? "igdb:" + g.cover.image_id : null,
      v: dev,
      m: [...new Set((g.game_modes || []).map((m) => MODES[m.slug]).filter(Boolean))],
      sm: short(g.summary),
    };
  }

  // Keyset pagination (id > last id) is stable and avoids offset limits.
  async function pull(where, label, map) {
    let lastId = 0;
    let added = 0;
    for (let page = 1; page <= MAX_PAGES; page++) {
      const rows = await q("games", `fields ${FIELDS}; where ${where} & id > ${lastId}; sort id asc; limit 500;`);
      for (const r of rows) {
        const before = map.size;
        upsert(map, compact(r));
        if (map.size > before) added++;
      }
      if (rows.length < 500) break;
      lastId = rows[rows.length - 1].id;
      process.stdout.write(".");
    }
    console.log(` ${label}: +${added}`);
  }

  const now = Math.floor(Date.now() / 1000);
  const recent = now - 180 * 86400;
  const base = `platforms = (${ids}) & version_parent = null & name != null`;
  const notable = `(total_rating_count >= ${MIN_RATINGS} | hypes >= 3 | first_release_date >= ${recent})`;

  const full = FULL_FLAG || !existing || existing.source !== "IGDB";
  const games = new Map((full ? [] : existing.games).map((g) => [g.id, g]));

  if (full) {
    process.stdout.write("Full download");
    await pull(`${base} & ${notable}`, "games", games);
  } else {
    const since = Math.floor(new Date(existing.updated).getTime() / 1000) - 86400;
    process.stdout.write(`Updating games changed since ${isoDay(new Date(since * 1000))}`);
    await pull(`${base} & updated_at >= ${since} & ${notable}`, "new or changed", games);
  }
  return save(games, "IGDB");
}

/* ==========================================================================
   RAWG
   ========================================================================== */

async function runRAWG(existing) {
  const KEY = env("RAWG_API_KEY");
  const BASE = env("RAWG_API_BASE") || "https://api.rawg.io/api";
  const MIN_ADDED = Number(env("MIN_ADDED") || 15);

  async function api(endpoint, params = {}) {
    const url = `${BASE}/${endpoint}?` + new URLSearchParams({ key: KEY, ...params });
    for (let attempt = 1; ; attempt++) {
      requests++;
      let res;
      try {
        res = await fetch(url, { headers: { "User-Agent": "Cartridge/1.0 (game library build script)" } });
      } catch (err) {
        if (attempt >= 4) throw err;
        await sleep(1000 * attempt);
        continue;
      }
      if (res.ok) return res.json();
      if (res.status === 401 || res.status === 403) throw new Error(`RAWG rejected the API key (HTTP ${res.status}). Check RAWG_API_KEY in .env.`);
      if ((res.status === 429 || res.status >= 500) && attempt < 5) { await sleep(1500 * attempt); continue; }
      throw new Error(`RAWG request failed: HTTP ${res.status} for ${endpoint}${res.status >= 520 ? " (RAWG's servers appear to be down)" : ""}`);
    }
  }

  const rawgToOurs = new Map();
  for (let page = 1; ; page++) {
    const data = await api("platforms", { page_size: "50", page: String(page) });
    for (const p of data.results || []) {
      const ours = matchPlatform(p.name);
      if (ours) rawgToOurs.set(p.id, ours);
    }
    if (!data.next) break;
  }
  const found = [...new Set(rawgToOurs.values())];
  const missing = Object.keys(PLATFORM_NAMES).filter((p) => !found.includes(p));
  console.log(`Matched ${found.length} Nintendo systems on RAWG.` + (missing.length ? ` Not found: ${missing.join(", ")}` : ""));

  const MODE_TAGS = {
    singleplayer: "solo", multiplayer: "multi", "co-op": "coop", cooperative: "coop", "online-co-op": "coop",
    "local-co-op": "local", "local-multiplayer": "local", "split-screen": "local", "online-multiplayer": "online",
  };
  const compact = (r) => ({
    id: r.slug,
    t: r.name,
    d: r.released || null,
    p: [...new Set((r.platforms || []).map((x) => rawgToOurs.get(x.platform?.id)).filter(Boolean))],
    g: [...new Set((r.genres || []).map((x) => x.name))],
    s: r.metacritic ?? null,
    r: r.rating ? Math.round(r.rating * 100) / 100 : 0,
    rc: r.ratings_count || 0,
    a: r.added || 0,
    i: r.background_image ? r.background_image.replace("https://media.rawg.io/media/", "~/") : null,
    e: r.esrb_rating?.name ?? null,
    m: [...new Set((r.tags || []).map((t) => MODE_TAGS[t.slug]).filter(Boolean))],
  });

  async function eachPage(params, onResult, stopWhen) {
    for (let page = 1; page <= MAX_PAGES; page++) {
      const data = await api("games", { ...params, page_size: "40", page: String(page) });
      let stop = false;
      for (const r of data.results || []) {
        if (stopWhen && stopWhen(r)) { stop = true; break; }
        onResult(r);
      }
      if (stop || !data.next) return;
      if (page % 10 === 0) process.stdout.write(".");
    }
  }

  const full = FULL_FLAG || !existing || existing.source !== "RAWG";
  const games = new Map((full ? [] : existing.games).map((g) => [g.id, g]));
  const allIds = [...rawgToOurs.keys()].join(",");
  const add = (r) => upsert(games, compact(r));

  if (full) {
    console.log(`Full download (games added by at least ${MIN_ADDED} RAWG users)...`);
    for (const [rawgId, ours] of rawgToOurs) {
      const before = games.size;
      process.stdout.write(`  ${ours.padEnd(8)}`);
      await eachPage({ platforms: String(rawgId), ordering: "-added" }, add, (r) => (r.added || 0) < MIN_ADDED);
      console.log(` +${games.size - before}`);
    }
  } else {
    const since = existing.updated.slice(0, 10);
    console.log(`Updating games changed since ${since}...`);
    await eachPage({ platforms: allIds, updated: `${since},${isoDay(new Date(Date.now() + DAY))}`, ordering: "-updated" }, (r) => {
      if (games.has(r.slug) || (r.added || 0) >= MIN_ADDED) add(r);
    });
  }
  const before = games.size;
  await eachPage({ platforms: allIds, dates: `${isoDay(new Date(Date.now() - 120 * DAY))},${isoDay(new Date(Date.now() + 365 * DAY))}`, ordering: "-added" }, add, (r) => (r.added || 0) < 2);
  console.log(`Recent & upcoming releases: +${games.size - before}`);
  return save(games, "RAWG");
}

/* ==========================================================================
   Main
   ========================================================================== */

async function main() {
  const started = Date.now();
  const igdb = !placeholder(env("IGDB_CLIENT_ID")) && !placeholder(env("IGDB_CLIENT_SECRET"));
  const rawg = !placeholder(env("RAWG_API_KEY"));
  if (!igdb && !rawg) {
    console.error([
      "No API keys found. Create a .env file in the project folder with either:",
      "",
      "  IGDB_CLIENT_ID=...        (free, from https://dev.twitch.tv/console)",
      "  IGDB_CLIENT_SECRET=...",
      "",
      "or",
      "",
      "  RAWG_API_KEY=...          (free, from https://rawg.io/apidocs)",
    ].join("\n"));
    process.exit(1);
  }
  const existing = readExisting();
  const { count, kb } = igdb ? await runIGDB(existing) : await runRAWG(existing);
  console.log(`\nSaved ${count} games to data/library.js (${kb} KB) using ${requests} API requests in ${Math.round((Date.now() - started) / 1000)}s.`);
}

main().catch((err) => {
  console.error("\n" + err.message);
  process.exit(1);
});
