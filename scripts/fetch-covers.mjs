// Regenerates data/covers.js from Wikipedia.
// Run after adding or renaming games:  node scripts/fetch-covers.mjs
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "data/games.js"), "utf8"), ctx);
const games = ctx.window.GAMES;

const API = "https://en.wikipedia.org/w/api.php";
const HEADERS = { "User-Agent": "GlassSwitchUi/1.0 (cover art build script)" };
const SIZE = 600;
const clean = (u) => u.split("?")[0];

async function query(params) {
  const res = await fetch(API + "?" + new URLSearchParams({ action: "query", format: "json", formatversion: "2", ...params }), { headers: HEADERS });
  if (!res.ok) throw new Error(`Wikipedia API ${res.status}`);
  return res.json();
}

const covers = {};
const problems = [];

// 1. Article lead images (the infobox cover art).
const articleGames = games.filter((g) => !g.image);
const titles = [...new Set(articleGames.map((g) => g.wiki || g.title))];
for (let i = 0; i < titles.length; i += 50) {
  const batch = titles.slice(i, i + 50);
  const data = await query({
    redirects: "1", prop: "pageimages", piprop: "thumbnail", pilicense: "any",
    pithumbsize: String(SIZE), titles: batch.join("|"),
  });
  const alias = {};
  for (const n of data.query.normalized || []) alias[n.from] = n.to;
  for (const r of data.query.redirects || []) alias[r.from] = r.to;
  const byTitle = Object.fromEntries(data.query.pages.map((p) => [p.title, p]));
  for (const t of batch) {
    let k = alias[t] || t;
    k = alias[k] || k;
    const p = byTitle[k];
    if (p && p.thumbnail) covers[t] = [clean(p.thumbnail.source), p.thumbnail.width, p.thumbnail.height];
    else problems.push(`${t}: ${!p || p.missing ? "page not found" : "no lead image"}`);
  }
}

// 2. Explicit image files (game.image).
for (const g of games.filter((x) => x.image)) {
  const data = await query({ prop: "imageinfo", iiprop: "url|size", iiurlwidth: String(SIZE), titles: "File:" + g.image });
  const info = data.query.pages[0]?.imageinfo?.[0];
  if (info) covers[g.wiki || g.title] = [clean(info.thumburl || info.url), info.thumbwidth || info.width, info.thumbheight || info.height];
  else problems.push(`${g.title}: image file not found (${g.image})`);
}

const out = "/* Generated by scripts/fetch-covers.mjs. Do not edit by hand. */\nwindow.COVERS = " + JSON.stringify(covers, null, 0).replace(/\],"/g, '],\n"') + ";\n";
fs.writeFileSync(path.join(root, "data/covers.js"), out);
console.log(`Wrote ${Object.keys(covers).length} covers for ${games.length} games.`);
if (problems.length) console.log("Without cover art (a styled fallback is shown):\n  " + problems.join("\n  "));
